const site = process.argv[2];
const read = f => fs.readFileSync(path.join(site, 'src/js', f), 'utf8');
const constants = read('core/constants/001-constants.js');
function cnst(name) {
  const at = constants.indexOf('const ' + name + ' =');
  let i = constants.indexOf('=', at) + 1, depth = 0, q = null;
  for (; i < constants.length; i++) {
    const c = constants[i];
    if (q) { if (c === '\\') { i++; continue; } if (c === q) q = null; continue; }
    if (c === '/' && constants[i + 1] === '/') { i = constants.indexOf('\n', i); continue; }
    if (c === '"' || c === "'" || c === '`') { q = c; continue; }
    if ('[{('.includes(c)) depth++; else if (']})'.includes(c)) depth--;
    else if (c === ';' && depth === 0) break;
  }
  return constants.slice(at, i + 1).replace(/^const /, 'var ') + '\n';
}
const snap = read('services/cloud-sync/004-v115-cloud-data-loss-prevention-recovery-guard.js');
const snapFn = snap.slice(snap.indexOf('function snapshot(){'), snap.indexOf('\n}', snap.indexOf('function snapshot(){')) + 2);
const NOW = 1762600000000;
