// Generates lib/src/ui/theme_catalog.dart from the website's own theme
// definitions (every html[data-theme="…"] block in its CSS and theme scripts),
// so the app offers exactly the website's themes with the same colours.
//
//   node tool/website_reference/generate_themes.mjs <MediaFlow website checkout>
import fs from 'node:fs';
import path from 'node:path';

const site = process.argv[2];
if (!site) { console.error('usage: generate_themes.mjs <website checkout>'); process.exit(2); }
const files = [];
const walk = d => { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); const st = fs.statSync(p);
  if (st.isDirectory()) walk(p); else if (/\.(css|js)$/.test(f) && !/bundle/.test(f)) files.push(p); } };
walk(path.join(site, 'assets/css')); walk(path.join(site, 'src/js'));
files.sort();
const vars = new Map(); const glow = new Map();
const hex = s => { s = s.trim().toLowerCase();
  let m = s.match(/^#([0-9a-f]{6})$/); if (m) return '#' + m[1];
  m = s.match(/^#([0-9a-f]{3})$/); if (m) return '#' + [...m[1]].map(c => c + c).join('');
  m = s.match(/^rgba?\(\s*(\d+)[ ,]+(\d+)[ ,]+(\d+)/); if (m) return '#' + [m[1], m[2], m[3]].map(v => (+v).toString(16).padStart(2, '0')).join('');
  if (s === '#fff' || s === 'white') return '#ffffff'; if (s === 'black') return '#000000';
  return null; };
const mix = (a, p, b) => { const x = parseInt(a.slice(1), 16), y = parseInt(b.slice(1), 16), w = p / 100;
  const c = [16, 8, 0].map(sh => Math.round(((x >> sh) & 255) * w + ((y >> sh) & 255) * (1 - w)));
  return '#' + c.map(v => v.toString(16).padStart(2, '0')).join(''); };
for (const f of files) {
  const text = fs.readFileSync(f, 'utf8');
  for (const m of text.matchAll(/html\[data-theme=["']?([\w-]+)["']?\]\s*\{([^}]*)\}/g)) {
    const id = m[1], body = m[2];
    const v = vars.get(id) || {}; vars.set(id, v);
    for (const d of body.matchAll(/--([\w-]+)\s*:\s*([^;]+)/g)) v[d[1]] = d[2].replace(/!important/, '').trim();
  }
  for (const m of text.matchAll(/html\[data-theme=["']?([\w-]+)["']?\]\s+body\s*\{\s*background:\s*(?:radial|linear)-gradient\(([^;]*)\)/g)) {
    const c = m[2].match(/#[0-9a-fA-F]{3,6}\b/); if (c && !glow.has(m[1])) glow.set(m[1], hex(c[0]));
  }
}
// :root (the default dark theme) from the foundation stylesheet.
const root = {}; const foundation = fs.readFileSync(path.join(site, 'assets/css/00-foundation.css'), 'utf8');
for (const m of foundation.matchAll(/:root\s*\{([^}]*)\}/g)) for (const d of m[1].matchAll(/--([\w-]+)\s*:\s*([^;]+)/g)) root[d[1]] ??= d[2].trim();
const resolve = (v, own) => { if (!v) return null; v = v.trim();
  const h = hex(v); if (h) return h;
  let m = v.match(/^var\(--([\w-]+)\)$/); if (m) return resolve(own[m[1]] ?? root[m[1]], own);
  m = v.match(/^color-mix\(in srgb,\s*([^ ]+)\s+(\d+(?:\.\d+)?)%\s*,\s*([^)]+)\)$/);
  if (m) { const a = resolve(m[1], own), b = resolve(m[3], own); return a && b ? mix(a, +m[2], b) : null; }
  return null; };
const src = fs.readFileSync(path.join(site, 'src/js/features/themes/029-v63-original-50-theme-collection.js'), 'utf8');
const list = JSON.parse(src.match(/const V43_THEMES=(\[[^\]]*\])/)[1].replace(/'/g, '"'));
const labels = Function('return ' + src.match(/const V43_THEME_LABELS=(\{[^}]*\})/)[1])();
const v101 = fs.readFileSync(path.join(site, 'src/js/features/themes/036-v101-full-style-themes-runtime-scope-fix.js'), 'utf8');
const full = JSON.parse(v101.match(/const FULL_STYLE_THEMES=(\[[^\]]*\])/)[1].replace(/'/g, '"'));
Object.assign(labels, Function('return ' + v101.match(/const FULL_STYLE_LABELS=(\{[^}]*\})/)[1])());
const ids = [...new Set([...list, ...full])].filter(id => id !== 'custom');
const rows = [];
for (const id of ids) {
  const own = { ...(vars.get(id) || {}) };
  const get = k => resolve(own[k] ?? (id === 'dark' ? root[k] : root[k]), own);
  const row = { id, label: labels[id] || id.replace(/^(platform|fullstyle)-/, '').replace(/-/g, ' ').replace(/\b\w/g, c => c.toUpperCase()),
    group: id.startsWith('platform-') ? 'platform' : id.startsWith('fullstyle-') ? 'fullstyle' : 'mediaflow',
    bg: get('bg'), panel: get('panel'), raised: get('panel-raised'), border: get('border'), text: get('text'),
    dim: get('text-dim'), mute: get('text-mute'), flow: get('flow'), glow: glow.get(id) || null };
  if (!vars.has(id) && id !== 'dark') console.warn('no colours found for', id, '(uses the default)');
  rows.push(row);
}
const c = s => s ? `0xFF${s.slice(1).toUpperCase()}` : 'null';
const q = s => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const out = `// GENERATED by tool/website_reference/generate_themes.mjs from the MediaFlow
// website's theme definitions. Do not edit by hand.

import 'theme_palette.dart';

/// Every built-in website theme (MediaFlow, Platform and Full Style), in the
/// website's order, with its exact colours.
const List<ThemeDef> kWebsiteThemes = [
${rows.map(r => `  ThemeDef(${q(r.id)}, ${q(r.label)}, ${q(r.group)}, bg: ${c(r.bg)}, panel: ${c(r.panel)}, raised: ${c(r.raised)}, border: ${c(r.border)}, text: ${c(r.text)}, dim: ${c(r.dim)}, mute: ${c(r.mute)}, flow: ${c(r.flow)}, glow: ${c(r.glow)}),`).join('\n')}
];
`;
fs.writeFileSync(path.join(path.dirname(new URL(import.meta.url).pathname), '../../lib/src/ui/theme_catalog.dart'), out);
console.log('themes:', rows.length, 'mediaflow', rows.filter(r => r.group === 'mediaflow').length, 'platform', rows.filter(r => r.group === 'platform').length, 'fullstyle', rows.filter(r => r.group === 'fullstyle').length);
console.log('root flow', root['flow'], 'bg', root['bg']);
