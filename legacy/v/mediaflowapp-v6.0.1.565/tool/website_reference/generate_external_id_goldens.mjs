// lib/src/logic/external_id_providers.g.dart (the website's v377 External
// Media ID list) and test/fixtures/external-ids-golden.json (v377IdValid on
// sample values).
//   node tool/website_reference/generate_external_id_goldens.mjs <website checkout>
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const site = process.argv[2];
const src = fs.readFileSync(path.join(site, 'src/js/components/273-v377-ids-editor-jikan-recovery.js'), 'utf8');
const list = src.slice(src.indexOf('const V377_ID_PROVIDERS'), src.indexOf('];', src.indexOf('const V377_ID_PROVIDERS')) + 2);
const valid = src.slice(src.indexOf('const v377IdValid'), src.indexOf('};', src.indexOf('const v377IdValid')) + 2);
const ctx = { URL };
vm.createContext(ctx);
vm.runInContext(list.replace('const ', 'var ') + valid.replace('const ', 'var '), ctx);
const providers = JSON.parse(JSON.stringify(ctx.V377_ID_PROVIDERS));
const values = ['', '1', '0', '012', '52991', 'abc', 'tt0111161', 'tt12', 'Q42', 'q0', '10.1000/xyz123', '10.1/x', 'a1b2c3d4-e5f6-4a7b-8c9d-0e1f2a3b4c5d',
  '978-0-306-40615-7', '0306406152', '030640615X', '12345-6789', 'https://www.royalroad.com/fiction/syndication/123', 'http://x.example/a', 'with space',
  'slug-name_1.2:3', 'x'.repeat(121), 'ab/c'];
const cases = [];
for (const [key] of providers) for (const v of values) cases.push([key, v, ctx.v377IdValid(key, v)]);
const here = path.dirname(new URL(import.meta.url).pathname);
fs.writeFileSync(path.join(here, '../../test/fixtures/external-ids-golden.json'), JSON.stringify({ providers, cases }) + '\n');
const dart = `// GENERATED by tool/website_reference/generate_external_id_goldens.mjs from the
// website's V377_ID_PROVIDERS (key, label, placeholder). Do not edit by hand.

const kExternalIdProviders = <(String, String, String)>[
${providers.map(p => `  (${p.map(x => JSON.stringify(x).replace(/\$/g, '\\$')).join(', ')}),`).join('\n')}
];
`;
fs.writeFileSync(path.join(here, '../../lib/src/logic/external_id_providers.g.dart'), dart);
console.log(providers.length, 'providers', cases.length, 'cases');
